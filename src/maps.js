// `options` er base64(zlib(JSON-streng med base64)). Innholdet er én byte med antall,
// og deretter oppføringer på formen <lengde, 4 byte LE><"nøkkel:verdi">.
export function parseOptions(options) {
  const inner = Buffer.from(JSON.parse(zlib.inflateSync(Buffer.from(options, 'base64')).toString()), 'base64');
  const out = {};
  for (let p = 1; p + 4 <= inner.length;) {
    const len = inner.readUInt32LE(p);
    const entry = inner.subarray(p + 4, p + 4 + len).toString();
    const i = entry.indexOf(':');
    if (i > 0) out[entry.slice(0, i)] = entry.slice(i + 1);
    p += 4 + len;
  }
  return out;
}

// Kartnavnet fra `options`, eller null hvis det mangler eller id-en er ukjent.
// Etter Return of Rome (nøkkel 97 finnes) ligger kartet i nøkkel 10, før det i nøkkel 11.
export function mapFromOptions(options) {
  if (!options) return null;
  try {
    const o = parseOptions(options);
    return MAP_NAMES[o['97'] != null ? o['10'] : o['11']] ?? null;
  } catch {
    return null;
  }
}
